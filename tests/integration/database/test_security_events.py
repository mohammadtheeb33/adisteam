async def test_find_events_by_host(migrated_database: Database) -> None:
    ours = [_at(minute, host_id="web-1") for minute in range(5)]
    theirs = _at(2, host_id="db-1")
    await _store(migrated_database, *ours, theirs)

    async with migrated_database.session() as session:
        repository = SecurityEventRepository(session)
        everything = await repository.find_events_by_host("web-1")
        window = await repository.find_events_by_host(
            "web-1", since=T0 + timedelta(minutes=1), until=T0 + timedelta(minutes=4)
        )
        latest_two = await repository.find_events_by_host("web-1", limit=2)
        nobody = await repository.find_events_by_host("unknown-host")

    newest_first = [event.event_id for event in reversed(ours)]
    assert [record.event_id for record in everything] == newest_first
    assert [record.event_id for record in window] == [
        e.event_id for e in (ours[3], ours[2], ours[1])
    ]
    assert [record.event_id for record in latest_two] == newest_first[:2]
    assert nobody == []


async def test_find_events_by_time_range(migrated_database: Database) -> None:
    events = [_at(minute) for minute in range(6)]
    other_type = _at(3, event_type="system.boot")
    await _store(migrated_database, *events, other_type)

    async with migrated_database.session() as session:
        repository = SecurityEventRepository(session)
        start, end = T0 + timedelta(minutes=1), T0 + timedelta(minutes=4)
        newest = await repository.find_events_by_time_range(start, end)
        oldest = await repository.find_events_by_time_range(start, end, newest_first=False)
        typed = await repository.find_events_by_time_range(start, end, event_type="system.boot")
        limited = await repository.find_events_by_time_range(start, end, limit=1)

    in_range = {events[1].event_id, events[2].event_id, events[3].event_id, other_type.event_id}
    assert {record.event_id for record in newest} == in_range
    assert [record.timestamp for record in oldest] == sorted(r.timestamp for r in oldest)
    assert [record.timestamp for record in newest] == sorted(
        (r.timestamp for r in newest), reverse=True
    )
    assert [record.event_id for record in typed] == [other_type.event_id]
    assert len(limited) == 1
    assert limited[0].timestamp == T0 + timedelta(minutes=3)
