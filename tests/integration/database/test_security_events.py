async def test_store_event_is_idempotent(migrated_database: Database) -> None:
    event = parse_canonical_event(network())

    async with migrated_database.transaction() as session:
        repository = SecurityEventRepository(session)
        first, second = await repository.store_event(event), await repository.store_event(event)
    async with migrated_database.session() as session:
        count = await session.scalar(select(func.count()).select_from(SecurityEventRecord))

    assert (first, second, count) == (True, False, 1)


async def test_stored_columns_and_payload(migrated_database: Database) -> None:
    event = parse_canonical_event(network(severity_hint="medium"))
    await _store(migrated_database, event)

    async with migrated_database.session() as session:
        record = await SecurityEventRepository(session).find_event(event.event_id)

    assert record is not None
    assert record.id.version == 7
    assert (record.timestamp, record.received_at) == (event.timestamp, event.received_at)
    assert record.timestamp.tzinfo is not None
    assert (record.event_type, record.source_type, record.host_id) == (
        "network.flow",
        "agent",
        "web-1",
    )
    assert (record.src_ip, record.dst_ip) == (IPv4Address("10.0.0.5"), IPv4Address("10.0.0.9"))
    assert (record.src_port, record.dst_port, record.protocol) == (51_514, 443, "tcp")
    assert record.severity_hint == "medium"
    assert record.agent_id is None
    assert record.created_at is not None
    assert record.to_canonical() == event


async def test_every_category_round_trips(migrated_database: Database) -> None:
    events = [parse_canonical_event(builder()) for builder in BUILDERS.values()]
    await _store(migrated_database, *events)

    async with migrated_database.session() as session:
        repository = SecurityEventRepository(session)
        restored = [await repository.find_event(event.event_id) for event in events]

    assert [record.to_canonical() if record else None for record in restored] == events


async def test_ipv6_addresses_and_zone_ids(migrated_database: Database) -> None:
    event = parse_canonical_event(authentication(src_ip="fe80::1%eth0", dst_ip="2001:db8::9"))
    await _store(migrated_database, event)

    async with migrated_database.session() as session:
        record = await SecurityEventRepository(session).find_event(event.event_id)

    assert record is not None
    assert (record.src_ip, record.dst_ip) == (IPv6Address("fe80::1"), IPv6Address("2001:db8::9"))
    assert record.payload["src_ip"] == "fe80::1%eth0"


async def test_batch_reports_new_and_duplicate_events(migrated_database: Database) -> None:
    stored, fresh = _at(0), _at(1)
    await _store(migrated_database, stored)

    async with migrated_database.transaction() as session:
        result = await SecurityEventRepository(session).store_events_batch([stored, fresh, fresh])

    assert result.inserted == (fresh.event_id,)
    assert result.duplicates == (stored.event_id, fresh.event_id)


async def test_large_batches_are_stored_in_one_call(migrated_database: Database) -> None:
    events = [_at(minute) for minute in range(1_500)]

    async with migrated_database.transaction() as session:
        result = await SecurityEventRepository(session).store_events_batch(events)

    assert len(result.inserted) == 1_500


async def _store_then_fail(database: Database, event: AnyCanonicalEvent) -> None:
    async with database.transaction() as session:
        await SecurityEventRepository(session).store_event(event)
        raise RuntimeError("abort unit of work")


async def test_failed_unit_of_work_stores_nothing(migrated_database: Database) -> None:
    event = _at(0)

    with pytest.raises(RuntimeError, match="abort unit of work"):
        await _store_then_fail(migrated_database, event)

    async with migrated_database.session() as session:
        assert await SecurityEventRepository(session).find_event(event.event_id) is None


