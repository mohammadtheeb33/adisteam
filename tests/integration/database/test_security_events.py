async def test_only_registered_agents_are_linked(migrated_database: Database) -> None:
    agent = await _register_agent(migrated_database)
    linked = _at(0, agent_id=str(agent.id))
    unknown = _at(1, agent_id=str(uuid4()))
    free_form = _at(2, agent_id="agent-7")
    await _store(migrated_database, linked, unknown, free_form)

    async with migrated_database.session() as session:
        repository = SecurityEventRepository(session)
        records = [await repository.find_event(e.event_id) for e in (linked, unknown, free_form)]

    assert [record.agent_id if record else "missing" for record in records] == [
        agent.id,
        None,
        None,
    ]
    assert records[1] is not None
    assert records[1].payload["agent_id"] == unknown.agent_id


async def test_deleting_an_agent_keeps_its_events(migrated_database: Database) -> None:
    agent = await _register_agent(migrated_database)
    event = _at(0, agent_id=str(agent.id))
    await _store(migrated_database, event)

    async with migrated_database.transaction() as session:
        repository = AgentRepository(session)
        stored = await repository.get(agent.id)
        assert stored is not None
        await repository.delete(stored)
    async with migrated_database.session() as session:
        record = await SecurityEventRepository(session).find_event(event.event_id)

    assert record is not None
    assert record.agent_id is None


async def test_agent_defaults_and_update_timestamp(migrated_database: Database) -> None:
    agent = await _register_agent(migrated_database)

    assert agent.status is AgentStatus.PENDING
    assert agent.first_seen is None
    assert agent.created_at == agent.updated_at

    async with migrated_database.transaction() as session:
        stored = await AgentRepository(session).get(agent.id)
        assert stored is not None
        stored.status = AgentStatus.ACTIVE
        stored.first_seen = stored.last_seen = datetime.now(UTC)
        await session.flush()
        updated_at = stored.updated_at

    assert updated_at > agent.updated_at


