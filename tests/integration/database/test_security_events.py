async def test_expected_indexes_exist(migrated_database: Database) -> None:
    async with migrated_database.session() as session:
        rows = await session.execute(
            text(
                "SELECT indexname, indexdef FROM pg_indexes "
                "WHERE schemaname = 'adis' AND tablename = 'security_events'"
            )
        )
        indexes = {str(name): str(definition) for name, definition in rows}

    assert set(indexes) == {
        "pk_security_events",
        "uq_security_events_event_id",
        "ix_security_events_timestamp",
        "ix_security_events_received_at_brin",
        "ix_security_events_event_type_timestamp",
        "ix_security_events_host_id_timestamp",
        "ix_security_events_agent_id_timestamp",
        "ix_security_events_src_ip",
        "ix_security_events_dst_ip",
    }
    assert "USING brin" in indexes["ix_security_events_received_at_brin"]
    assert "WHERE (host_id IS NOT NULL)" in indexes["ix_security_events_host_id_timestamp"]


async def test_row_level_security_is_enabled(migrated_database: Database) -> None:
    async with migrated_database.session() as session:
        rows = await session.execute(
            text(
                "SELECT c.relname, c.relrowsecurity FROM pg_class c "
                "JOIN pg_namespace n ON n.oid = c.relnamespace "
                "WHERE n.nspname = 'adis' AND c.relname IN ('agents', 'security_events')"
            )
        )

    assert dict(rows.all()) == {"agents": True, "security_events": True}


