T0 = datetime(2026, 9, 25, 12, tzinfo=UTC)


def _at(minutes: int, **overrides: object) -> AnyCanonicalEvent:
    moment = (T0 + timedelta(minutes=minutes)).isoformat()
    return parse_canonical_event(system(timestamp=moment, **overrides))


async def _store(database: Database, *events: AnyCanonicalEvent) -> None:
    async with database.transaction() as session:
        await SecurityEventRepository(session).store_events_batch(list(events))


async def _register_agent(database: Database) -> AgentRecord:
    async with database.transaction() as session:
        return AgentRepository(session).add(
            AgentRecord(
                name="agent-web-1", hostname="web-1", os_type=OsType.LINUX, agent_version="1.0.0"
            )
        )


